"""Fetch the reader's bundled fonts (PLAN.md 8.5) into app/src/main/assets/reader/fonts.

All are under the SIL Open Font License 1.1; each family's licence goes next to its
files. Five come from the @fontsource npm packages (pinned versions below), OpenDyslexic
from its upstream repository (the commit used is recorded in SOURCE.txt). Only the latin and latin-ext subsets
are kept, in weights 400 and 700, upright and italic; other scripts fall back to the
system serif. Writes fonts/fonts.css with one @font-face per file.

    python3 -I app/tools/fetch_reader_fonts.py
"""
import io
import json
import pathlib
import sys
import tarfile
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1] / "src/main/assets/reader/fonts"
UA = "Bibliotheke-build (https://github.com/polemistes/bibliotheke; develop@robertemilberge.no)"

FONTSOURCE = {
    # id: (family name in CSS, package version)
    "literata": ("Literata", "5.3.0"),
    "eb-garamond": ("EB Garamond", "5.3.0"),
    "noto-serif": ("Noto Serif", "5.3.0"),
    "source-sans-3": ("Source Sans 3", "5.3.1"),
    "atkinson-hyperlegible": ("Atkinson Hyperlegible", "5.3.0"),
}
SUBSETS = ["latin-ext", "latin"]
STYLES = [(400, "normal"), (700, "normal"), (400, "italic"), (700, "italic")]

OPENDYSLEXIC = {
    (400, "normal"): "OpenDyslexic-Regular.woff2",
    (700, "normal"): "OpenDyslexic-Bold.woff2",
    (400, "italic"): "OpenDyslexic-Italic.woff2",
    (700, "italic"): "OpenDyslexic-Bold-Italic.woff2",
}


def get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    for attempt in range(5):
        try:
            with urllib.request.urlopen(req, timeout=60) as r:
                return r.read()
        except OSError as e:
            if attempt == 4:
                raise
            print(f"retry {url}: {e}", file=sys.stderr)
    raise AssertionError


def face(family: str, weight: int, style: str, path: str, unicode_range: str | None) -> str:
    rng = f"\n  unicode-range: {unicode_range};" if unicode_range else ""
    return (
        f"@font-face {{\n  font-family: '{family}';\n  font-style: {style};\n  font-weight: {weight};\n"
        f"  font-display: block;\n  src: url({path}) format('woff2');{rng}\n}}\n"
    )


def main() -> int:
    css = ["/* Generated by app/tools/fetch_reader_fonts.py; SIL OFL 1.1, see each folder. */\n"]
    for fid, (family, version) in FONTSOURCE.items():
        tgz = get(f"https://registry.npmjs.org/@fontsource/{fid}/-/{fid}-{version}.tgz")
        out = ROOT / fid
        out.mkdir(parents=True, exist_ok=True)
        with tarfile.open(fileobj=io.BytesIO(tgz)) as tar:
            ranges = json.load(tar.extractfile("package/unicode.json"))
            (out / "OFL.txt").write_bytes(tar.extractfile("package/LICENSE").read())
            for weight, style in STYLES:
                for subset in SUBSETS:
                    name = f"{fid}-{subset}-{weight}-{style}.woff2"
                    (out / name).write_bytes(tar.extractfile(f"package/files/{name}").read())
                    css.append(face(family, weight, style, f"{fid}/{name}", ranges[subset]))
        print(f"{family} {version}")

    sha = json.loads(get("https://api.github.com/repos/antijingoist/opendyslexic/commits/main"))["sha"]
    base = f"https://raw.githubusercontent.com/antijingoist/opendyslexic/{sha}"
    out = ROOT / "opendyslexic"
    out.mkdir(parents=True, exist_ok=True)
    (out / "OFL.txt").write_bytes(get(f"{base}/OFL.txt"))
    for (weight, style), name in OPENDYSLEXIC.items():
        (out / name).write_bytes(get(f"{base}/compiled/{name}"))
        css.append(face("OpenDyslexic", weight, style, f"opendyslexic/{name}", None))
    (out / "SOURCE.txt").write_text(f"https://github.com/antijingoist/opendyslexic commit {sha}\n")
    print(f"OpenDyslexic {sha[:10]}")

    (ROOT / "fonts.css").write_text("\n".join(css))
    return 0


if __name__ == "__main__":
    sys.exit(main())
